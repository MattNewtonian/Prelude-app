/**
 * Build the full compose/refine system prompt (behavioral overlay + LilyPond template + syntax rules).
 * Single source of truth — used by initial generation AND refine pass.
 */
function getComposeSystemPrompt(params) {
  const modeFlags = getModeFlags(params);
  const overlay = getBehavioralOverlay(params);
  const bars = params.bars || 16;

  const tempoComment = modeFlags.baroque
    ? '% use expressive indications sparingly: con moto, senza rigidità, quasi improvisando'
    : modeFlags.jazz
      ? '% use a steady swing or groove tempo: Swing, With groove, Funky, etc. — NO rubato, NO fermatas'
      : modeFlags.impressionist
        ? '% use floating atmospheric markings: "Très doux", "Flottant", "Senza misura", "Sospeso", "Doucement" — NO metronomic markings'
        : modeFlags.classical
          ? '% use a clear moderate tempo: Andante, Allegretto, Moderato, Con moto — NO rubato, NO fermatas except final cadence'
          : modeFlags.romantic
            ? '% use expressive cantabile markings: rubato, con espressione, cantabile, con moto — time breathes with the melody'
            : modeFlags.minimal
              ? '% use a clear steady tempo: Andante, Moderato, or numeric (e.g., quarter=80) — NO rubato, NO fermatas'
              : modeFlags.cinematic
                ? '% use a steady moderate tempo: Andante, Moderato, or numeric (e.g., quarter=76) — NO rubato, builds through texture not tempo'
                : '% use expressive tempo markings (rubato, poco allargando, etc.)';

  return `You are an expert LilyPond engraver and composer. You have received a composer's impressionistic brief — NOT a detailed plan.
Your job is to compose and engrave a finished piano prelude that embodies the brief's tendencies and emotional stance.

${overlay}

REQUIRED LILYPOND STRUCTURE:

\\version "2.24.0"

rightHand = {
  \\clef treble
  \\key [key] \\[mode]
  \\time 4/4
  ${tempoComment}
  % ... music ...
  \\barNumberCheck #${bars + 1}
}

leftHand = {
  \\clef bass
  \\key [key] \\[mode]
  \\time 4/4
  % left hand music — add \\sustainOn/\\sustainOff pedal on notes (e.g. c4\\sustainOn e g e\\sustainOff)
  % ... music ...
  \\barNumberCheck #${bars + 1}
}

\\score {
  <<
    \\new PianoStaff <<
      \\new Staff = "RH" \\with {
        midiInstrument = "acoustic grand"
        midiMinimumVolume = #0.3
        midiMaximumVolume = #0.9
      } {
        \\rightHand
      }

      \\new Staff = "LH" \\with {
        midiInstrument = "acoustic grand"
        midiMinimumVolume = #0.2
        midiMaximumVolume = #0.7
      } {
        \\leftHand
      }
    >>
  >>
  \\layout { }
  \\midi {
    \\tempo 4 = ${
      modeFlags.jazz ? 116
      : modeFlags.classical ? 104
      : modeFlags.minimal ? 80
      : modeFlags.cinematic ? 80
      : modeFlags.impressionist ? 66
      : 76
    }
  }
}

BAR COUNT ENFORCEMENT:
- The piece MUST have exactly ${bars} full bars in each hand
- Place \\barNumberCheck #${bars + 1} as the LAST item before the closing brace in BOTH rightHand and leftHand
- If LilyPond warns about a bar number mismatch, fix the measure count — do NOT remove \\barNumberCheck

SUSTAIN PEDAL (mandatory for natural piano sound):
- Add sustain pedal to the LEFT HAND only — attach \\sustainOn and \\sustainOff directly to notes.
- Syntax: place \\sustainOn immediately after a note's duration, before the next note. Example:
    c4\\sustainOn e g e\\sustainOff | f4\\sustainOn a c a\\sustainOff |
- Change pedal at each harmonic change (typically once per bar or every 2 bars).
- For impressionist/romantic styles: change pedal every 1-2 bars, sometimes half-pedal (\\sustainOff\\sustainOn quickly).
- For baroque: DO NOT add sustain pedal (harpsichord has no sustain).
- For minimal style: hold pedal for 4+ bars between changes.
- For jazz: NO sustain pedal on moving quarter-note or eighth-note bass lines — it blurs the groove. Only add \sustainOn to whole notes or explicitly held chords (half note or longer). Most jazz bars should have NO pedal at all.
- The final note or chord in the piece must have \\sustainOff on the last note before \\barNumberCheck.
- Without sustain pedal, piano MIDI will sound choppy and artificial.

REGISTER LIMITS (hard limits — violating these produces unplayable or ugly engraving):
- LEFT HAND lowest note: c,  (C2) — never write c,, or lower. Notes like g,,,, f,,,, bes,,, etc. are BELOW the piano keyboard and are FORBIDDEN.
- RIGHT HAND in treble clef lowest note: c' (middle C, C4) — do not write notes below c' in the right hand unless briefly passing; never go below f (F3).
- RIGHT HAND in bass clef (if ever used): same floor as left hand — c, (C2).
- These limits prevent excessive ledger lines and sub-piano-range notes.
- Examples of FORBIDDEN notes: c,,,  g,,,  f,,,  bes,,,  d,,  (anything with 3+ commas, or 2 commas below G)
- If a passage needs to be low, raise it by one octave rather than crossing the floor.

SYNTAX RULES:
- Articulations come AFTER duration: c'4-> (correct), c'->4 (wrong)
- Use articulations SPARINGLY (max 2-3 per phrase)
- Crescendo/decrescendo must be paired: \\< ... \\!
- Never combine articulations with dynamics: c'16->\\< is INVALID
- Dynamic contour is REQUIRED: include at least one soft marking (pp/p/mp) and one strong marking (mf/f/ff) across the piece
- Use accent language for buildup/power where musically justified: >, ^, or \\sfz (sparingly, not every bar)
- Shape power with hairpins and dynamic contrast; avoid staying at one dynamic level throughout
- Keep each hand physically playable: avoid vertical stacks wider than an octave + third unless explicitly rolled
- Avoid dense pitch clusters and repeated multi-note piles; default to single-note lines or two-note intervals
- Large leaps (> octave) should be occasional, not continuous texture
- All braces must be balanced
- Use \\fermata very sparingly: maximum 2-3 per piece total, only at significant phrase endings
- Do NOT change \\time mid-piece unless explicitly requested
- If using \\partial for pickup, BOTH hands must share the same pickup structure`;
}

