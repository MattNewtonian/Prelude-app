/**
 * PASS B: Generate LilyPond from Plan
 */
async function generateLilyPondFromPlan(plan, params, conversationHistory = [], costTracking) {
  const { system, user } = buildLilypondFromPlanPrompt(plan, params);

  const messages = conversationHistory.length > 0
    ? conversationHistory
    : [{ role: 'user', content: user }];

  // Safety guard: check API call limit
  checkAPICallLimit(costTracking);

  // Calculate request size
  const requestSize = system.length + messages.reduce((sum, msg) => sum + msg.content.length, 0);

  const response = await anthropic.messages.create({
    model: 'claude-sonnet-4-5-20250929',
    max_tokens: 4096,
    system: system,
    messages: messages
  });

  const content = response.content[0].text;

  // Track this API call
  const callType = conversationHistory.length > 0 ? 'repair' : 'generate';
  trackAPICall(costTracking, callType, requestSize, content.length);

  // Extract LilyPond code
  let lilypondCode = content;
  const codeBlockMatch = content.match(/```(?:lilypond)?\n([\s\S]*?)```/);
  if (codeBlockMatch) {
    lilypondCode = codeBlockMatch[1].trim();
  }

  return {
    code: lilypondCode,
    conversationHistory: [...messages, { role: 'assistant', content }]
  };
}

