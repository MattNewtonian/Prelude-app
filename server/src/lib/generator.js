/**
 * Safety guard: Check if we've exceeded max API calls
 */
function checkAPICallLimit(costTracking) {
  if (costTracking.totalCalls >= MAX_TOTAL_CLAUDE_CALLS) {
    throw new Error(
      `Safety limit exceeded: job reached ${MAX_TOTAL_CLAUDE_CALLS} API calls. ` +
      `This prevents runaway costs. Adjust MAX_TOTAL_CLAUDE_CALLS if needed.`
    );
  }
}

/**
 * Cost tracking helper
 * Approximate tokens: chars / 4 (rough estimate)
 */
function trackAPICall(costTracking, callType, requestChars, responseChars) {
  const approxInputTokens = Math.ceil(requestChars / 4);
  const approxOutputTokens = Math.ceil(responseChars / 4);

  costTracking.calls.push({
    type: callType,
    requestChars,
    responseChars,
    approxInputTokens,
    approxOutputTokens
  });

  costTracking.totalCalls++;
  costTracking.totalInputTokens += approxInputTokens;
  costTracking.totalOutputTokens += approxOutputTokens;
}

/**
 * Initialize cost tracking object
 */
function createCostTracking() {
  return {
    calls: [],
    totalCalls: 0,
    totalInputTokens: 0,
    totalOutputTokens: 0
  };
}

/**
 * Normalize free text to keep prompts concise and token-efficient.
 */
function compactPromptText(text, maxLength = 240) {
  if (!text || typeof text !== 'string') return '';

  const compact = text.replace(/\s+/g, ' ').trim();
  if (compact.length <= maxLength) return compact;

  return compact.slice(0, maxLength - 3).trimEnd() + '...';
}

/**
 * Build provenance markup block for LilyPond PDF.
 * Appears as a small, muted info block above the score.
 */
function buildProvenanceMarkup(params) {
  const { key, bars, difficulty, style, inspiredBy, prompt } = params;

  const year = new Date().getFullYear();
  const diffLabel = difficulty.charAt(0).toUpperCase() + difficulty.slice(1);

  // Escape for LilyPond string literals
  function escapeLy(str) {
    return str.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  }

  // Truncate prompt if needed
  let shortPrompt = (prompt || '').trim();
  if (shortPrompt.length > 120) {
    shortPrompt = shortPrompt.substring(0, 117).trim() + '...';
  }

  // Get display names for style and composer
  const styleName = style ? (getStylePreset(style)?.name || style) : null;
  const composerName = inspiredBy ? (getComposerInspiration(inspiredBy)?.name || inspiredBy) : null;

  // Build content lines for the markup block
  const lines = [];

  if (shortPrompt) {
    lines.push('"Generated from a natural-language description:"');
    lines.push('\\italic { "' + escapeLy('\u201C' + shortPrompt + '\u201D') + '" }');
    lines.push('\\vspace #0.3');
  }

  lines.push('"Key: ' + escapeLy(key) + ' \u00B7 Bars: ' + bars + ' \u00B7 Difficulty: ' + diffLabel + '"');

  if (styleName) {
    lines.push('"Style: ' + escapeLy(styleName) + '"');
  }
  if (composerName) {
    lines.push('"Inspiration: ' + escapeLy(composerName) + '"');
  }

  lines.push('\\vspace #0.3');
  lines.push('"Generated by Prelude \u00B7 ' + year + '"');

  const indented = lines.map(l => '      ' + l).join('\n');

  return [
    '',
    '\\markup \\fill-line {',
    '  \\center-column {',
    "    \\fontsize #-2 \\with-color #(x11-color 'grey50) \\center-column {",
    indented,
    '    }',
    '    \\vspace #1',
    '  }',
    '}',
    ''
  ].join('\n');
}

/**
 * Inject provenance markup into LilyPond code, before the \\score block.
 */
function injectProvenance(code, provenanceMarkup) {
  const scoreIndex = code.indexOf('\\score');
  if (scoreIndex !== -1) {
    return code.substring(0, scoreIndex) + provenanceMarkup + '\n' + code.substring(scoreIndex);
  }
  // Fallback: prepend after version line
  const versionEnd = code.indexOf('\n');
  if (versionEnd !== -1) {
    return code.substring(0, versionEnd + 1) + provenanceMarkup + '\n' + code.substring(versionEnd + 1);
  }
  return provenanceMarkup + '\n' + code;
}

/**
 * Detect active behavioral mode flags for a given params object.
 * Returns { baroque, organicTime, antiEtude } booleans.
 * Low threshold — better to over-trigger than under-trigger.
 */
export function getModeFlags(params) {
  const { style, inspiredBy, prompt } = params;

  // Baroque detection: check all three sources
  let baroque = false;
  if (style && ['baroque', 'keyboard', 'partita'].includes(style.toLowerCase())) baroque = true;
  if (inspiredBy && inspiredBy.toLowerCase() === 'bach') baroque = true;
  if (prompt) {
    const lower = prompt.toLowerCase();
    const keywords = [
      'bach', 'partita', 'fugue', 'invention', 'baroque', 'contrapuntal',
      'counterpoint', 'prelude and fugue', 'well-tempered', 'toccata',
      'sarabande', 'allemande', 'courante', 'gigue', 'bourrée', 'bourree',
      'gavotte', 'minuet', 'passacaglia', 'chaconne', 'ricercar', 'sinfonia'
    ];
    if (keywords.some(k => lower.includes(k))) baroque = true;
  }

  return {
    baroque,
    organicTime: !baroque,   // default mode when not baroque
    antiEtude: !baroque       // default mode when not baroque
  };
}

/**
 * Get the behavioral overlay string for the current mode.
 * Used by plan, compose, and refine prompts.
 */
function getBehavioralOverlay(params) {
  const modeFlags = getModeFlags(params);
  return modeFlags.baroque ? BAROQUE_COMPOSE_INSTRUCTIONS : DEFAULT_COMPOSE_INSTRUCTIONS;
}

