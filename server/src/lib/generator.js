/**
 * Deterministic post-check: detect static LH patterns and harmonic stasis.
 * Returns an array of issue descriptions, or empty array if clean.
 */
function checkStaticPatterns(lilypondCode) {
  const issues = [];

  // Extract left hand content between leftHand = { ... }
  const lhMatch = lilypondCode.match(/leftHand\s*=\s*\{([\s\S]*?)\n\}/);
  if (!lhMatch) return issues;

  const lhContent = lhMatch[1];

  // Normalize: strip comments, collapse whitespace
  const normalized = lhContent
    .replace(/%[^\n]*/g, '')
    .replace(/\\(clef|key|time|bar)\b[^\n]*/g, '')
    .replace(/\s+/g, ' ')
    .trim();

  // Split into bars by barcheck '|' or by rough note groupings
  const bars = normalized.split('|').map(b => b.trim()).filter(b => b.length > 0);

  if (bars.length < 3) return issues;

  // Check for 3+ consecutive identical bars (static LH)
  let consecutiveIdentical = 1;
  for (let i = 1; i < bars.length; i++) {
    if (bars[i] === bars[i - 1]) {
      consecutiveIdentical++;
      if (consecutiveIdentical >= 3) {
        issues.push(`Static left hand: bars ${i - 1}-${i + 1} are identical ("${bars[i].substring(0, 40)}...")`);
        break;
      }
    } else {
      consecutiveIdentical = 1;
    }
  }

  // Check for harmonic stasis: same pitch classes repeated across 4+ bars
  // Extract pitch letters (ignoring octave marks and durations)
  const barPitches = bars.map(bar => {
    const pitches = bar.match(/[a-g](?:is|es|isis|eses)?/g);
    return pitches ? pitches.sort().join(',') : '';
  });

  let consecutiveSamePitches = 1;
  for (let i = 1; i < barPitches.length; i++) {
    if (barPitches[i] && barPitches[i] === barPitches[i - 1]) {
      consecutiveSamePitches++;
      if (consecutiveSamePitches >= 4) {
        issues.push(`Harmonic stasis: left hand uses identical pitch classes for ${consecutiveSamePitches} consecutive bars around bar ${i + 1}`);
        break;
      }
    } else {
      consecutiveSamePitches = 1;
    }
  }

  return issues;
}

/**
 * Post-generation validation: time signatures and pickup measures.
 * Returns { valid, warnings } — warnings are logged but don't block output.
 */
function validateLilypondOutput(lilypondCode) {
  const warnings = [];

  // Count \time occurrences (excluding comments)
  const noComments = lilypondCode.replace(/%[^\n]*/g, '');
  const timeMatches = noComments.match(/\\time\s+\d+\/\d+/g) || [];
  const timeSignaturesCount = timeMatches.length;

  if (timeSignaturesCount > 2) {
    // 2 is expected (one per staff), more means mid-piece changes
    warnings.push(`Multiple \\time signatures detected (${timeSignaturesCount}). Possible mid-piece time change.`);
  }

  // Check for \partial — both hands must match
  const rhMatch = lilypondCode.match(/rightHand\s*=\s*\{([\s\S]*?)\n\}/);
  const lhMatch = lilypondCode.match(/leftHand\s*=\s*\{([\s\S]*?)\n\}/);
  const hasPartial = noComments.includes('\\partial');

  if (hasPartial && rhMatch && lhMatch) {
    const rhPartial = (rhMatch[1].match(/\\partial\s+\S+/) || [null])[0];
    const lhPartial = (lhMatch[1].match(/\\partial\s+\S+/) || [null])[0];

    if (rhPartial && !lhPartial) {
      warnings.push('Pickup (\\partial) in RH but not LH — MIDI may be misaligned.');
    } else if (!rhPartial && lhPartial) {
      warnings.push('Pickup (\\partial) in LH but not RH — MIDI may be misaligned.');
    } else if (rhPartial && lhPartial && rhPartial !== lhPartial) {
      warnings.push(`Mismatched pickups: RH has "${rhPartial}", LH has "${lhPartial}".`);
    }
  }

  // Check \barNumberCheck presence
  const hasBarCheck = noComments.includes('\\barNumberCheck');

  return {
    valid: warnings.length === 0,
    warnings,
    timeSignaturesCount,
    hasPartial,
    hasBarCheck
  };
}

/**
 * PASS A: Build Composer Plan Prompt (constraint-first, NO LilyPond)
 */
function buildComposerPlanPrompt(params) {
  const {
    key,
    bars,
    difficulty,
    style,
    inspiredBy,
    prompt,
    intent,
    motifMode,
    harmonyBudget,
    surpriseType,
    negativeConstraints
  } = params;

  // Default intent if not provided (CRITICAL for quality)
  const composerIntent = intent ||
    "Compose a prelude built from a small idea that resists closure until the final bars.";

  const stylePreset = style ? getStylePreset(style) : null;
  const composer = inspiredBy ? getComposerInspiration(inspiredBy) : null;

  // Determine harmony budget level
  const harmonyLevel = harmonyBudget || (stylePreset?.harmonyBudget) || 'normal';

  const philosophyBlock = getPlanBehavioralOverlay(params);

  let systemPrompt = `You are a composer sketching a brief for a piano prelude. You do NOT write notation yet.
You output a short, impressionistic JSON brief - NOT a detailed structural analysis.

${philosophyBlock}

CRITICAL: Output a SHORT impressionistic brief, not a detailed narrated plan.
The brief should feel like a composer's private sketch - suggestive, not exhaustive.

MANDATORY OUTPUT FORMAT:
{
  "tendencies": ["2-3 vague musical tendencies, e.g. 'harmony drifts between two distant tonal centers'"],
  "emotion": "one sentence describing the emotional stance or character",
  "avoid": "one sentence naming what the piece must NOT do or sound like"
}

Output ONLY the JSON. No explanations, no markdown, no code blocks.`;

  // Add harmony budget constraints
  systemPrompt += `\n\nHARMONY BUDGET: ${harmonyLevel.toUpperCase()}`;

  if (harmonyLevel === 'tight') {
    systemPrompt += `
- Diatonic harmony ONLY
- Maximum ONE borrowed chord allowed
- NO modulation
- State exact cadence plan with roman numerals`;
  } else if (harmonyLevel === 'normal') {
    systemPrompt += `
- One modulation allowed
- 2-3 chromatic events total
- Must state cadence plan with roman numerals`;
  } else if (harmonyLevel === 'rich') {
    systemPrompt += `
- Color harmony allowed
- Still MUST state explicit cadence plan with roman numerals
- Chromatic enrichment must serve structure, not decoration`;
  }

  // Add difficulty-based harmonic rhythm guidance
  if (difficulty === 'beginner') {
    systemPrompt += `\n\nHARMONIC RHYTHM: Slow (~1 change per 2 bars). Harmonic stability is primary.`;
  } else if (difficulty === 'intermediate') {
    systemPrompt += `\n\nHARMONIC RHYTHM: Moderate (1-2 changes per bar). Balance motion with clarity.`;
  } else if (difficulty === 'advanced') {
    systemPrompt += `\n\nHARMONIC RHYTHM: Variable but deliberate. May shift every beat in climactic passages, hold for bars in static passages. The rate of change itself is a compositional tool.`;
  }

  // Add motif mode constraints (OBSESSIVE MODE)
  if (motifMode === true) {
    systemPrompt += `\n\nOBSESSIVE MOTIF MODE (HARD CONSTRAINTS):
- The motif MUST appear every 1-2 bars
- NO new rhythmic cells after bar 8
- Transformations are REQUIRED (not optional)
- Melody derives from motif, accompaniment reacts to it
- Favor memorability and intentional limitation over continuous novelty`;
  }

  // Add structural surprise constraint
  systemPrompt += `\n\nSTRUCTURAL SURPRISE:
Choose EXACTLY ONE surprise from: extra bar, deceptive cadence, phrase truncation, register displacement.
${surpriseType ? `Preference: ${surpriseType}` : 'Default to phrase truncation if unsure.'}
Do NOT add more than one surprise.`;

  // Add style preset constraints
  if (stylePreset) {
    systemPrompt += `\n\nSTYLE CONSTRAINTS: ${stylePreset.name.toUpperCase()}
Phrase Rules: ${stylePreset.constraints.phrase}
Texture: ${stylePreset.constraints.texture}
Harmony: ${stylePreset.constraints.harmony}
Avoid: ${stylePreset.constraints.avoid.join(', ')}`;
  }

  // Add composer inspiration (thinking habits, not sound-alikes)
  if (composer) {
    systemPrompt += `\n\nCOMPOSER THINKING HABIT:
${composer.name}: ${composer.hint}
This describes a way of thinking, not a sound to copy.`;
  }

  // Build user prompt
  let userPrompt = `MUSICAL PROBLEM:\n${composerIntent}

SPECIFICATIONS:
- Key: ${key}
- Bars: ${bars}
- Difficulty: ${difficulty}`;

  if (prompt) {
    userPrompt += `
- User direction: ${compactPromptText(prompt)}`;
  }

  if (negativeConstraints) {
    userPrompt += `\n\nAVOID (HARD CONSTRAINTS):\n${negativeConstraints}`;
  }

  userPrompt += `\n\nGenerate the JSON composer plan now.`;

  return {
    system: systemPrompt,
    user: userPrompt
  };
}

/**
 * PASS A: Generate Composer Plan (JSON only, no LilyPond)
 */
async function generateComposerPlan(params, progressCallback, costTracking) {
  const { system, user } = buildComposerPlanPrompt(params);

  let parseAttempt = 0;

  while (parseAttempt < MAX_PLAN_PARSE_ATTEMPTS) {
    parseAttempt++;

    progressCallback?.({
      message: `Generating composer plan (attempt ${parseAttempt})...`,
      progress: 5 + (parseAttempt * 5)
    });

    try {
      // Safety guard: check API call limit
      checkAPICallLimit(costTracking);

      // Calculate request size
      const requestSize = system.length + user.length;

      const response = await anthropic.messages.create({
        model: 'claude-sonnet-4-5-20250929',
        max_tokens: 512,
        system: system,
        messages: [{ role: 'user', content: user }]
      });

      let content = response.content[0].text.trim();

      // Track this API call
      trackAPICall(costTracking, 'plan-generate', requestSize, content.length);

      // Strip markdown code blocks if present
      content = content.replace(/^```json?\s*\n?/i, '').replace(/\n?```\s*$/i, '');

      // Parse JSON
      const plan = JSON.parse(content);

      // Validate required fields (new impressionistic brief format)
      const requiredFields = ['tendencies', 'emotion', 'avoid'];
      for (const field of requiredFields) {
        if (!plan[field]) {
          throw new Error(`Missing required field: ${field}`);
        }
      }
      if (!Array.isArray(plan.tendencies) || plan.tendencies.length < 2) {
        throw new Error('tendencies must be an array with at least 2 items');
      }

      console.log('[Composer Plan] ✓ Valid plan generated');
      console.log(JSON.stringify(plan, null, 2));

      return plan;

    } catch (error) {
      console.warn(`[Composer Plan] Parse attempt ${parseAttempt} failed:`, error.message);

      if (parseAttempt >= MAX_PLAN_PARSE_ATTEMPTS) {
        throw new Error(`Failed to generate valid composer plan after ${MAX_PLAN_PARSE_ATTEMPTS} attempts: ${error.message}`);
      }

      // Brief delay before retry
      await new Promise(resolve => setTimeout(resolve, 1000));
    }
  }
}

/**
 * PASS B: Build LilyPond Generation Prompt (from plan)
 */
function buildLilypondFromPlanPrompt(plan, params) {
  const { key, bars, difficulty } = params;
  const systemPrompt = getComposeSystemPrompt(params);

  const userPrompt = `COMPOSER BRIEF:
${JSON.stringify(plan)}

SPECIFICATIONS:
- Key: ${key}
- Bars: ${bars}
- Difficulty: ${difficulty}

Compose a piano prelude that embodies this brief. The brief gives tendencies and an emotional stance — not a blueprint.
Let the music emerge from these constraints. Do not illustrate them literally.
Honor the "avoid" field strictly.

Output only the complete LilyPond code.`;

  return {
    system: systemPrompt,
    user: userPrompt
  };
}

/**
 * PASS B: Generate LilyPond from Plan
 */
async function generateLilyPondFromPlan(plan, params, conversationHistory = [], costTracking) {
  const { system, user } = buildLilypondFromPlanPrompt(plan, params);

  const messages = conversationHistory.length > 0
    ? conversationHistory
    : [{ role: 'user', content: user }];

  // Safety guard: check API call limit
  checkAPICallLimit(costTracking);

  // Calculate request size
  const requestSize = system.length + messages.reduce((sum, msg) => sum + msg.content.length, 0);

  const response = await anthropic.messages.create({
    model: 'claude-sonnet-4-5-20250929',
    max_tokens: 4096,
    system: system,
    messages: messages
  });

  const content = response.content[0].text;

  // Track this API call
  const callType = conversationHistory.length > 0 ? 'repair' : 'generate';
  trackAPICall(costTracking, callType, requestSize, content.length);

  // Extract LilyPond code
  let lilypondCode = content;
  const codeBlockMatch = content.match(/```(?:lilypond)?\n([\s\S]*?)```/);
  if (codeBlockMatch) {
    lilypondCode = codeBlockMatch[1].trim();
  }

  return {
    code: lilypondCode,
    conversationHistory: [...messages, { role: 'assistant', content }]
  };
}

/**
 * OPTIONAL REFINE PASS
 * Uses lightweight haiku model to improve musicality after successful compilation
 */
async function refineLilyPond(lilypondCode, plan, params, costTracking) {
  const modeFlags = getModeFlags(params);
  const modeName = modeFlags.baroque ? 'Baroque mode' : 'Organic Time / Anti-Étude mode';

  // Use the SAME behavioral overlay as initial generation
  const systemPrompt = getComposeSystemPrompt(params) + `

REFINE PASS CONSTRAINTS:
- Do NOT change the harmonic plan, form, or bar count
- Do NOT rewrite the music — only make subtle refinements
- Focus on: voice leading smoothness, dynamic shaping, articulation clarity
- Preserve all stylistic/behavioral constraints (${modeName}) — do NOT drift toward exercise phrasing
- Output ONLY the complete refined LilyPond code`;

  const userPrompt = `COMPOSER BRIEF:
${JSON.stringify(plan)}

CURRENT LILYPOND CODE:
${lilypondCode}

Make subtle refinements to improve musicality while preserving ${modeName} constraints. Output only the refined LilyPond code.`;

  // Safety guard: check API call limit
  checkAPICallLimit(costTracking);

  const requestSize = systemPrompt.length + userPrompt.length;

  const response = await anthropic.messages.create({
    model: 'claude-haiku-4-5-20251001',  // Use haiku for cost savings
    max_tokens: 4096,
    system: systemPrompt,
    messages: [{ role: 'user', content: userPrompt }]
  });

  const content = response.content[0].text;
  trackAPICall(costTracking, 'refine', requestSize, content.length);

  // Extract LilyPond code
  let refinedCode = content;
  const codeBlockMatch = content.match(/```(?:lilypond)?\n([\s\S]*?)```/);
  if (codeBlockMatch) {
    refinedCode = codeBlockMatch[1].trim();
  }

  return refinedCode;
}

/**
 * TWO-PASS GENERATION WITH REPAIR
 * Pass A: Composer Plan (never regenerated)
 * Pass B: LilyPond from Plan (repaired if needed)
 */
export async function generateWithRepair(params, progressCallback) {
  const {
    key,
    bars,
    difficulty,
    prompt,
    style,
    inspiredBy,
    jobId,
    // New optional parameters
    motifMode = false,
    intent = null,
    negativeConstraints = null,
    surpriseType = null,
    harmonyBudget = null,
    refine = false
  } = params;

  // DRAFT MODE: Cost-saving overrides for development
  const draftMode = process.env.PRELUDE_DRAFT_MODE === 'true';
  let effectiveBars = bars;
  let effectiveHarmonyBudget = harmonyBudget;
  let effectiveSurpriseType = surpriseType;
  let effectiveMaxRepairs = MAX_REPAIR_ATTEMPTS;

  if (draftMode) {
    effectiveBars = Math.min(bars, 12);
    effectiveHarmonyBudget = 'tight';
    effectiveSurpriseType = 'none';
    effectiveMaxRepairs = 2;

    console.log(`[draft-mode] bars capped to ${effectiveBars}, harmony=tight, surprise=none, repair attempts capped to ${effectiveMaxRepairs}`);
  }

  // Build extended spec with draft mode overrides
  const spec = {
    key,
    bars: effectiveBars,
    difficulty,
    prompt,
    style,
    inspiredBy,
    motifMode,
    intent,
    negativeConstraints,
    surpriseType: effectiveSurpriseType,
    harmonyBudget: effectiveHarmonyBudget
  };

  // Detect behavioral mode flags (single source of truth for this job)
  const modeFlags = getModeFlags(spec);
  console.log(`[job ${jobId}] modeFlags=${JSON.stringify(modeFlags)} bars=${effectiveBars} draft=${draftMode}`);

  // Initialize cost tracking
  const costTracking = createCostTracking();

  // Output paths
  const outputDir = path.resolve(__dirname, '../../outputs');
  const basename = `job-${jobId}`;
  const lyPath = path.join(outputDir, `${basename}.ly`);
  const planPath = path.join(outputDir, `${basename}-plan.json`);

  // CHECK CACHE FIRST (immediate cost savings)
  const cacheKey = generateCacheKey(params);
  const cachedResult = getCachedResult(cacheKey);

  if (cachedResult) {
    console.log(`[cache] Returning cached result for job ${jobId}`);
    console.log(`[job ${jobId}] calls=0 inTok≈0 outTok≈0 repairs=0 refine=${refine} draft=${draftMode} cache=hit`);

    progressCallback?.({ message: 'Using cached result...', progress: 100 });

    // Return cached outputs immediately - no API calls needed!
    return {
      success: true,
      outputs: cachedResult.outputs,
      plan: cachedResult.plan || null,
      metrics: {
        humanScore: null,
        humanNotes: null,
        cost: {
          calls: 0,
          approxInputTokens: 0,
          approxOutputTokens: 0,
          callDetails: []
        },
        repairs: 0,
        refine: refine,
        cacheHit: true,
        draftMode
      },
      attempts: 0,
      cacheHit: true,
      draftMode
    };
  }

  console.log(`[cache] MISS - generating new result for job ${jobId}`);

  // PASS A: Generate Composer Plan (ONCE, never regenerated)
  progressCallback?.({ message: 'Creating composer plan...', progress: 5 });

  // Check for cached plan (separate from full output cache)
  let composerPlan = getCachedPlan(cacheKey);

  if (!composerPlan) {
    composerPlan = await generateComposerPlan(spec, progressCallback, costTracking);
  } else {
    console.log(`[cache] Using cached composer plan`);
  }

  // Save plan to file for debugging
  await writeLilyPondFile(JSON.stringify(composerPlan, null, 2), planPath);

  progressCallback?.({ message: 'Composer plan created. Generating notation...', progress: 15 });

  // Build provenance markup for PDF
  const provenanceMarkup = buildProvenanceMarkup({
    key, bars: effectiveBars, difficulty, style, inspiredBy, prompt
  });

  // PASS B: Generate LilyPond from Plan (with repair loop)
  let attempt = 0;
  let conversationHistory = [];
  let lastError = null;
  const regenLog = [];  // Track static-pattern regen reasons

  while (attempt < effectiveMaxRepairs) {
    attempt++;

    try {
      // Generate LilyPond code from plan
      let { code, conversationHistory: newHistory } = await generateLilyPondFromPlan(
        composerPlan,
        spec,
        conversationHistory,
        costTracking
      );

      conversationHistory = newHistory;

      progressCallback?.({
        message: `Attempt ${attempt}: Generated notation, compiling...`,
        progress: 20 + (attempt * 20)
      });

      // Write to file (with provenance block above the score)
      await writeLilyPondFile(injectProvenance(code, provenanceMarkup), lyPath);

      progressCallback?.({
        message: `Attempt ${attempt}: Compiling LilyPond...`,
        progress: 30 + (attempt * 20)
      });

      // Try to compile
      let outputs = await compileLilyPond(lyPath, outputDir);

      // OPTIONAL REFINE PASS: Improve musicality with lightweight model
      if (refine) {
        progressCallback?.({
          message: 'Refining musicality...',
          progress: 65
        });

        try {
          const refinedCode = await refineLilyPond(code, composerPlan, spec, costTracking);

          // Write refined code to file (with provenance block above the score)
          await writeLilyPondFile(injectProvenance(refinedCode, provenanceMarkup), lyPath);

          progressCallback?.({
            message: 'Recompiling refined notation...',
            progress: 68
          });

          // Recompile with refined code
          const refinedOutputs = await compileLilyPond(lyPath, outputDir);

          // Use refined outputs
          outputs = refinedOutputs;
          code = refinedCode;

          console.log('[Refine] ✓ Musicality refinement successful');
        } catch (refineError) {
          console.warn('[Refine] Refinement failed, using original code:', refineError.message);
          // Fall back to original code - already compiled and working
          await writeLilyPondFile(injectProvenance(code, provenanceMarkup), lyPath);
        }
      }

      // POST-CHECK: Detect static patterns and trigger single regen if needed
      const staticIssues = checkStaticPatterns(code);
      if (staticIssues.length > 0 && regenLog.length === 0) {
        // Only attempt one static-pattern regen per job
        regenLog.push({
          timestamp: new Date().toISOString(),
          attempt,
          issues: staticIssues
        });

        console.log('[Static Check] Issues detected:', staticIssues);

        progressCallback?.({
          message: 'Improving musical flow...',
          progress: 68
        });

        try {
          checkAPICallLimit(costTracking);

          const activeMode = modeFlags.baroque ? 'Baroque mode' : 'Organic Time / Anti-Étude mode';
          const fixPrompt = `The compiled LilyPond has static-pattern issues:\n${staticIssues.join('\n')}\n\nFix ONLY these issues:\n- Vary the left hand so no 3+ consecutive bars are identical\n- Introduce registral shifts, rhythmic variation, or harmonic change in flagged passages\n- Keep the overall structure, key, and bar count the same\n- Preserve the stylistic/behavioral constraints (${activeMode}). Only fix the flagged passages — do NOT rewrite the piece or drift toward exercise phrasing.\n- Output ONLY the complete corrected LilyPond code.`;

          const fixHistory = [
            ...conversationHistory,
            { role: 'user', content: fixPrompt }
          ];

          const requestSize = fixPrompt.length + conversationHistory.reduce((sum, msg) => sum + msg.content.length, 0);
          const fixResponse = await anthropic.messages.create({
            model: 'claude-sonnet-4-5-20250929',
            max_tokens: 4096,
            messages: fixHistory
          });

          const fixContent = fixResponse.content[0].text;
          trackAPICall(costTracking, 'static-fix', requestSize, fixContent.length);

          let fixedCode = fixContent;
          const fixCodeBlock = fixContent.match(/```(?:lilypond)?\n([\s\S]*?)```/);
          if (fixCodeBlock) {
            fixedCode = fixCodeBlock[1].trim();
          }

          // Write and recompile
          await writeLilyPondFile(injectProvenance(fixedCode, provenanceMarkup), lyPath);
          const fixedOutputs = await compileLilyPond(lyPath, outputDir);

          outputs = fixedOutputs;
          code = fixedCode;
          conversationHistory = [...fixHistory, { role: 'assistant', content: fixContent }];

          console.log('[Static Check] ✓ Fix applied successfully');
          regenLog[regenLog.length - 1].resolved = true;
        } catch (fixError) {
          console.warn('[Static Check] Fix failed, keeping original:', fixError.message);
          regenLog[regenLog.length - 1].resolved = false;
          regenLog[regenLog.length - 1].error = fixError.message;
          // Rewrite the original compiled code
          await writeLilyPondFile(injectProvenance(code, provenanceMarkup), lyPath);
        }
      } else if (staticIssues.length === 0) {
        console.log('[Static Check] ✓ No static patterns detected');
      }

      // Post-generation validation: time signatures, pickups, barNumberCheck
      const lyValidation = validateLilypondOutput(code);
      if (lyValidation.warnings.length > 0) {
        console.warn('[LY Validation]', lyValidation.warnings);
      }
      console.log(`[job ${jobId}] validation: timeSigs=${lyValidation.timeSignaturesCount} hasPartial=${lyValidation.hasPartial} barNumberCheck=${lyValidation.hasBarCheck}`);

      progressCallback?.({
        message: 'Compilation successful! Validating MIDI...',
        progress: 70
      });

      // Validate MIDI instrumentation
      if (outputs.midi) {
        const midiPath = outputs.midi;
        const validation = await validateMidi(midiPath);

        if (!validation.valid) {
          console.warn('[MIDI Validation] Failed:', validation.errors);
          console.log(getValidationReport(validation));
        } else {
          console.log('[MIDI Validation] ✓ Valid - Acoustic Grand Piano on multiple channels');
        }

        // Render audio with FluidSynth + Steinway soundfont
        progressCallback?.({
          message: 'Rendering audio with Steinway soundfont...',
          progress: 80
        });

        try {
          const audioOutputs = await renderAudio(midiPath, outputDir, {
            generateMP3: true
          });

          if (audioOutputs.wav) {
            outputs.wav = audioOutputs.wav;
          }
          if (audioOutputs.mp3) {
            outputs.mp3 = audioOutputs.mp3;
          }

          progressCallback?.({
            message: 'Audio rendering complete!',
            progress: 95
          });
        } catch (audioError) {
          console.warn('[Audio Rendering] Failed:', audioError.message);
          console.warn('[Audio Rendering] Continuing without audio files...');
        }
      }

      progressCallback?.({
        message: 'Generation complete!',
        progress: 100
      });

      // Analyze human-likeness (optional, display only)
      let metrics = null;
      try {
        metrics = analyzeHumanLikeness(code, composerPlan);
        console.log('[Human Metrics]', JSON.stringify(metrics, null, 2));
      } catch (metricsError) {
        console.warn('[Human Metrics] Analysis failed:', metricsError.message);
        // Continue without metrics - not critical
      }

      // Save regen log if any static-pattern fixes were attempted
      if (regenLog.length > 0) {
        const regenLogPath = path.join(outputDir, `${basename}-regen.json`);
        await writeLilyPondFile(JSON.stringify(regenLog, null, 2), regenLogPath);
        console.log(`[Static Check] Regen log saved to ${basename}-regen.json`);
      }

      // Save to cache for future requests
      const outputsToCache = {
        ly: `${basename}.ly`,
        pdf: path.basename(outputs.pdf),
        midi: outputs.midi ? path.basename(outputs.midi) : null,
        wav: outputs.wav ? path.basename(outputs.wav) : null,
        mp3: outputs.mp3 ? path.basename(outputs.mp3) : null,
        plan: `${basename}-plan.json`
      };

      await saveCacheEntry(cacheKey, outputsToCache, composerPlan);

      // Log cost summary
      console.log(`[job ${jobId}] calls=${costTracking.totalCalls} inTok≈${costTracking.totalInputTokens} outTok≈${costTracking.totalOutputTokens} repairs=${attempt - 1} refine=${refine} draft=${draftMode} cache=miss`);

      // Success! Return outputs with plan and metrics
      return {
        success: true,
        outputs: outputsToCache,
        plan: composerPlan,
        metrics: {
          humanScore: metrics?.humanScore || null,
          humanNotes: metrics?.notes || null,
          cost: {
            calls: costTracking.totalCalls,
            approxInputTokens: costTracking.totalInputTokens,
            approxOutputTokens: costTracking.totalOutputTokens,
            callDetails: costTracking.calls
          },
          repairs: attempt - 1,
          refine: refine,
          cacheHit: false,
          draftMode
        },
        attempts: attempt,
        cacheHit: false,
        draftMode
      };

    } catch (error) {
      lastError = error;

      progressCallback?.({
        message: `Attempt ${attempt}: Compilation failed, repairing notation...`,
        progress: 40 + (attempt * 15)
      });

      if (attempt >= effectiveMaxRepairs) {
        break;
      }

      // REPAIR PROMPT — preserves behavioral constraints
      const activeMode = modeFlags.baroque ? 'Baroque mode' : 'Organic Time / Anti-Étude mode';
      const repairPrompt = `You are fixing LilyPond compilation errors.

Task:
- Return a COMPLETE corrected LilyPond file.
- Make the smallest possible changes to fix the compile error.
- Do NOT rewrite the music unless required for correctness.
- Preserve key, time, bar count, and overall structure.
- Preserve the stylistic/behavioral constraints (${activeMode}). Only fix LilyPond syntax, bar counts, and rhythmic completeness.
- If \\barNumberCheck fails, adjust measures to match — do NOT remove \\barNumberCheck.

Constraints:
- LilyPond 2.24+.
- PianoStaff with RH/LH staves.
- No commentary, no explanations, no markdown.

Compiler error:
${error.message}

Current LilyPond:
${code}`;

      conversationHistory = [
        ...conversationHistory,
        { role: 'user', content: repairPrompt }
      ];

      await new Promise(resolve => setTimeout(resolve, 1000));
    }
  }

  // All attempts failed
  throw new Error(
    `Failed to generate valid LilyPond after ${effectiveMaxRepairs} attempts${draftMode ? ' (draft mode)' : ''}. Last error: ${lastError?.message || 'Unknown error'}`
  );
}
