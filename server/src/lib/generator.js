/**
 * Deterministic post-check: detect static LH patterns and harmonic stasis.
 * Returns an array of issue descriptions, or empty array if clean.
 */
function checkStaticPatterns(lilypondCode) {
  const issues = [];

  const noComments = lilypondCode.replace(/%[^\n]*/g, '');

  function normalizeHand(content) {
    return content
      .replace(/%[^\n]*/g, '')
      .replace(/\\(clef|key|time|tempo|bar|barNumberCheck)[^\n]*/g, '')
      .replace(/\s+/g, ' ')
      .trim();
  }

  function extractPitchClasses(content) {
    const notes = content.match(/\b[a-g](?:is|es|isis|eses)?/g) || [];
    return new Set(notes);
  }

  // ── Left hand checks ──
  const lhMatch = noComments.match(/leftHand\s*=\s*\{([\s\S]*?)\n\}/);
  if (lhMatch) {
    const lhNorm = normalizeHand(lhMatch[1]);
    const lhBars = lhNorm.split('|').map(b => b.trim()).filter(b => b.length > 0);

    if (lhBars.length >= 3) {
      // 3+ consecutive identical bars
      let consecutiveIdentical = 1;
      for (let i = 1; i < lhBars.length; i++) {
        if (lhBars[i] === lhBars[i - 1]) {
          consecutiveIdentical++;
          if (consecutiveIdentical >= 3) {
            issues.push(`Static left hand: bars ${i - 1}-${i + 1} are identical ("${lhBars[i].substring(0, 40)}...")`);
            break;
          }
        } else {
          consecutiveIdentical = 1;
        }
      }

      // Same pitch classes across 4+ consecutive bars
      const lhBarPitches = lhBars.map(bar => {
        const pitches = bar.match(/[a-g](?:is|es|isis|eses)?/g);
        return pitches ? [...new Set(pitches)].sort().join(',') : '';
      });
      let consecutiveSame = 1;
      for (let i = 1; i < lhBarPitches.length; i++) {
        if (lhBarPitches[i] && lhBarPitches[i] === lhBarPitches[i - 1]) {
          consecutiveSame++;
          if (consecutiveSame >= 4) {
            issues.push(`Harmonic stasis: left hand uses identical pitch classes for ${consecutiveSame} consecutive bars around bar ${i + 1}`);
            break;
          }
        } else {
          consecutiveSame = 1;
        }
      }
    }
  }

  // ── Right hand checks ──
  const rhMatch = noComments.match(/rightHand\s*=\s*\{([\s\S]*?)\n\}/);
  if (rhMatch) {
    const rhNorm = normalizeHand(rhMatch[1]);
    const rhBars = rhNorm.split('|').map(b => b.trim()).filter(b => b.length > 0);

    if (rhBars.length >= 3) {
      // 3+ consecutive identical bars in RH
      let consecutiveIdentical = 1;
      for (let i = 1; i < rhBars.length; i++) {
        if (rhBars[i] === rhBars[i - 1]) {
          consecutiveIdentical++;
          if (consecutiveIdentical >= 3) {
            issues.push(`Static right hand: bars ${i - 1}-${i + 1} are identical ("${rhBars[i].substring(0, 40)}...")`);
            break;
          }
        } else {
          consecutiveIdentical = 1;
        }
      }
    }

    // ── Global pitch variety check (both hands combined) ──
    const allPitches = extractPitchClasses(rhMatch[1] + (lhMatch ? lhMatch[1] : ''));
    const noteCount = (noComments.match(/\b[a-g](?:is|es|isis|eses)?[\d,']/g) || []).length;
    if (noteCount > 40 && allPitches.size < 4) {
      issues.push(
        `Extremely low pitch variety: only ${allPitches.size} distinct pitch class(es) used across the whole piece ` +
        `(${[...allPitches].join(', ')}). Add more harmonic color — at least 5-6 distinct pitches are needed.`
      );
    }

    // ── Simultaneous-rest (sparse texture) check ──
    if (lhMatch) {
      const lhNorm = normalizeHand(lhMatch[1]);
      const rhNorm = normalizeHand(rhMatch[1]);
      const lhBars = lhNorm.split('|').map(b => b.trim()).filter(b => b.length > 0);
      const rhBars = rhNorm.split('|').map(b => b.trim()).filter(b => b.length > 0);
      const minBars = Math.min(lhBars.length, rhBars.length);

      // A bar is "rest-heavy" if it contains no pitched notes or only a lone 8th note
      function isRestHeavy(bar) {
        const notes = (bar.match(/\b[a-g](?:is|es|isis|eses)?[\d,'"]/g) || []).length;
        return notes === 0 || (notes <= 1 && /r2\b|r1\b/.test(bar));
      }

      let simultaneousRestBars = 0;
      for (let i = 0; i < minBars; i++) {
        if (isRestHeavy(lhBars[i]) && isRestHeavy(rhBars[i])) {
          simultaneousRestBars++;
        }
      }

      const ratio = simultaneousRestBars / minBars;
      if (minBars >= 8 && ratio >= 0.30) {
        issues.push(
          `Sparse texture: both hands are simultaneously near-silent in ${simultaneousRestBars} of ${minBars} bars (${Math.round(ratio * 100)}%). ` +
          `When RH rests, LH must provide harmonic motion — and vice versa. Rewrite so at least one hand is always active.`
        );
      }
    }
  }

  // ── Fermata overuse check ──
  const fermataCount = (noComments.match(/\\fermata/g) || []).length;
  if (fermataCount > 4) {
    issues.push(
      `Fermata overuse: ${fermataCount} fermatas found. Maximum 3 per piece. ` +
      `Remove fermatas from mid-phrase rests — keep only 1-2 significant pauses.`
    );
  }

  // ── Tempo change overuse check ──
  const tempoCount = (noComments.match(/\\tempo\s+"/g) || []).length;
  // One \tempo is expected for the opening; anything beyond that is mid-piece changes
  const midPieceTempos = Math.max(0, tempoCount - 1);
  if (midPieceTempos > 3) {
    issues.push(
      `Tempo change overuse: ${midPieceTempos} mid-piece tempo changes found. Maximum 3 per piece. ` +
      `Constant tempo shifts (rubato → poco allargando → tempo sospeso every few bars) fragment the music. ` +
      `Consolidate to 1-2 expressive markings near phrase endings only.`
    );
  }

  // ── Sub-floor register check (notes below piano range or below ledger-line threshold) ──
  // LH floor: c, (C2) — anything with 3+ commas is below the piano keyboard
  // RH floor: f (F3) — anything below c' (middle C) in treble clef is excessive ledger lines
  const subFloorLH = (noComments.match(/[a-g](?:is|es|isis|eses)?,,,[,'"]*/g) || []);
  if (subFloorLH.length > 0) {
    issues.push(
      `Register too low: left hand has ${subFloorLH.length} note(s) below C2 (e.g. ${subFloorLH.slice(0,3).join(', ')}). ` +
      `These are below or at the limit of the piano keyboard and produce excessive ledger lines. ` +
      `Raise all left-hand notes with 3+ commas up by one octave.`
    );
  }
  // RH notes below F3 (f without any apostrophe, or with commas) in treble clef
  const subFloorRH = rhMatch
    ? (noComments.match(/\b[a-g](?:is|es|isis|eses)?(?:,+)[^']/g) || [])
    : [];
  if (subFloorRH.length > 2) {
    issues.push(
      `Right hand too low: ${subFloorRH.length} note(s) below C3 in treble clef (e.g. ${subFloorRH.slice(0,3).join(', ')}). ` +
      `Notes below middle C (c') in treble clef create many ledger lines. Raise these passages by an octave.`
    );
  }

  // ── RH phrase-starts-with-rest check (fragmented phrasing) ──
  if (rhMatch) {
    const rhNorm2 = normalizeHand(rhMatch[1]);
    const rhBars2 = rhNorm2.split('|').map(b => b.trim()).filter(b => b.length > 0);
    if (rhBars2.length >= 8) {
      const restStartCount = rhBars2.filter(bar => /^r[1248]\b/.test(bar)).length;
      const ratio = restStartCount / rhBars2.length;
      if (ratio >= 0.50) {
        issues.push(
          `Fragmented phrasing: ${restStartCount} of ${rhBars2.length} right-hand bars begin with a rest (${Math.round(ratio * 100)}%). ` +
          `This creates a "start-and-stop" effect. At most 1 in 3 bars should start with a rest. ` +
          `Begin phrases on pitched notes and use rests mid-phrase or at phrase ends instead.`
        );
      }
    }
  }

  return issues;
}

/**
 * Throw if compileLilyPond returned barcheck warnings.
 * Barcheck failures exit with code 0 but produce misaligned MIDI — treat as errors.
 */
function assertNoBarcheckFailures(outputs) {
  const warnings = outputs.barcheckWarnings;
  if (!warnings || warnings.length === 0) return;

  const details = warnings.map(w =>
    `Line ${w.line}: barcheck failed at position ${w.position} ` +
    `(bar has the wrong number of beats — off by ${w.position} in 4/4 time)`
  ).join('\n');

  throw new Error(
    `LilyPond barcheck failure — one or more bars have the wrong beat count:\n${details}\n\n` +
    `To fix: count the note and rest durations in the flagged bar(s). ` +
    `In 4/4 time every bar must total exactly 4 beats (16 sixteenth notes). ` +
    `Add or remove a rest/note to correct the total.`
  );
}

/**
 * Post-generation validation: time signatures and pickup measures.
 * Returns { valid, warnings } — warnings are logged but don't block output.
 */
function validateLilypondOutput(lilypondCode) {
  const warnings = [];

  // Count \time occurrences (excluding comments)
  const noComments = lilypondCode.replace(/%[^\n]*/g, '');
  const timeMatches = noComments.match(/\\time\s+\d+\/\d+/g) || [];
  const timeSignaturesCount = timeMatches.length;

  if (timeSignaturesCount > 2) {
    // 2 is expected (one per staff), more means mid-piece changes
    warnings.push(`Multiple \\time signatures detected (${timeSignaturesCount}). Possible mid-piece time change.`);
  }

  // Check for \partial — both hands must match
  const rhMatch = lilypondCode.match(/rightHand\s*=\s*\{([\s\S]*?)\n\}/);
  const lhMatch = lilypondCode.match(/leftHand\s*=\s*\{([\s\S]*?)\n\}/);
  const hasPartial = noComments.includes('\\partial');

  if (hasPartial && rhMatch && lhMatch) {
    const rhPartial = (rhMatch[1].match(/\\partial\s+\S+/) || [null])[0];
    const lhPartial = (lhMatch[1].match(/\\partial\s+\S+/) || [null])[0];

    if (rhPartial && !lhPartial) {
      warnings.push('Pickup (\\partial) in RH but not LH — MIDI may be misaligned.');
    } else if (!rhPartial && lhPartial) {
      warnings.push('Pickup (\\partial) in LH but not RH — MIDI may be misaligned.');
    } else if (rhPartial && lhPartial && rhPartial !== lhPartial) {
      warnings.push(`Mismatched pickups: RH has "${rhPartial}", LH has "${lhPartial}".`);
    }
  }

  // Check \barNumberCheck presence
  const hasBarCheck = noComments.includes('\\barNumberCheck');

  return {
    valid: warnings.length === 0,
    warnings,
    timeSignaturesCount,
    hasPartial,
    hasBarCheck
  };
}

/**
 * PASS A: Build Composer Plan Prompt (constraint-first, NO LilyPond)
 */
function buildComposerPlanPrompt(params) {
  const {
    key,
    bars,
    difficulty,
    style,
    inspiredBy,
    prompt,
    intent,
    motifMode,
    harmonyBudget,
    surpriseType,
    negativeConstraints
  } = params;

  // Default intent if not provided (CRITICAL for quality)
  const composerIntent = intent ||
    "Compose a prelude built from a small idea that resists closure until the final bars.";

  const stylePreset = style ? getStylePreset(style) : null;
  const composer = inspiredBy ? getComposerInspiration(inspiredBy) : null;

  // Determine harmony budget level
  const harmonyLevel = harmonyBudget || (stylePreset?.harmonyBudget) || 'normal';

  const philosophyBlock = getPlanBehavioralOverlay(params);

  let systemPrompt = `You are a composer sketching a brief for a piano prelude. You do NOT write notation yet.
You output a short, impressionistic JSON brief - NOT a detailed structural analysis.

${philosophyBlock}

CRITICAL: Output a SHORT impressionistic brief, not a detailed narrated plan.
The brief should feel like a composer's private sketch - suggestive, not exhaustive.

MANDATORY OUTPUT FORMAT:
{
  "tendencies": ["2-3 vague musical tendencies, e.g. 'harmony drifts between two distant tonal centers'"],
  "emotion": "one sentence describing the emotional stance or character",
  "avoid": "one sentence naming what the piece must NOT do or sound like"
}

Output ONLY the JSON. No explanations, no markdown, no code blocks.`;

  // Add harmony budget constraints
  systemPrompt += `\n\nHARMONY BUDGET: ${harmonyLevel.toUpperCase()}`;

  if (harmonyLevel === 'tight') {
    systemPrompt += `
- Diatonic harmony ONLY
- Maximum ONE borrowed chord allowed
- NO modulation
- State exact cadence plan with roman numerals`;
  } else if (harmonyLevel === 'normal') {
    systemPrompt += `
- One modulation allowed
- 2-3 chromatic events total
- Must state cadence plan with roman numerals`;
  } else if (harmonyLevel === 'rich') {
    systemPrompt += `
- Color harmony allowed
- Still MUST state explicit cadence plan with roman numerals
- Chromatic enrichment must serve structure, not decoration`;
  }

  // Add difficulty-based harmonic rhythm guidance
  if (difficulty === 'beginner') {
    systemPrompt += `\n\nHARMONIC RHYTHM: Slow (~1 change per 2 bars). Harmonic stability is primary.`;
  } else if (difficulty === 'intermediate') {
    systemPrompt += `\n\nHARMONIC RHYTHM: Moderate (1-2 changes per bar). Balance motion with clarity.`;
  } else if (difficulty === 'advanced') {
    systemPrompt += `\n\nHARMONIC RHYTHM: Variable but deliberate. May shift every beat in climactic passages, hold for bars in static passages. The rate of change itself is a compositional tool.`;
  }

  // Add motif mode constraints (OBSESSIVE MODE)
  if (motifMode === true) {
    systemPrompt += `\n\nOBSESSIVE MOTIF MODE (HARD CONSTRAINTS):
- The motif MUST appear every 1-2 bars
- NO new rhythmic cells after bar 8
- Transformations are REQUIRED (not optional)
- Melody derives from motif, accompaniment reacts to it
- Favor memorability and intentional limitation over continuous novelty`;
  }

  // Add structural surprise constraint
  systemPrompt += `\n\nSTRUCTURAL SURPRISE:
Choose EXACTLY ONE surprise from: extra bar, deceptive cadence, phrase truncation, register displacement.
${surpriseType ? `Preference: ${surpriseType}` : 'Default to phrase truncation if unsure.'}
Do NOT add more than one surprise.`;

  // Add style preset constraints
  if (stylePreset) {
    systemPrompt += `\n\nSTYLE CONSTRAINTS: ${stylePreset.name.toUpperCase()}
Phrase Rules: ${stylePreset.constraints.phrase}
Texture: ${stylePreset.constraints.texture}
Harmony: ${stylePreset.constraints.harmony}
Avoid: ${stylePreset.constraints.avoid.join(', ')}`;
  }

  // Add composer inspiration (thinking habits, not sound-alikes)
  if (composer) {
    systemPrompt += `\n\nCOMPOSER THINKING HABIT:
${composer.name}: ${composer.hint}
This describes a way of thinking, not a sound to copy.`;
  }

  // Build user prompt
  let userPrompt = `MUSICAL PROBLEM:\n${composerIntent}

SPECIFICATIONS:
- Key: ${key}
- Bars: ${bars}
- Difficulty: ${difficulty}`;

  if (prompt) {
    userPrompt += `
- User direction: ${compactPromptText(prompt)}`;
  }

  if (negativeConstraints) {
    userPrompt += `\n\nAVOID (HARD CONSTRAINTS):\n${negativeConstraints}`;
  }

  userPrompt += `\n\nGenerate the JSON composer plan now.`;

  return {
    system: systemPrompt,
    user: userPrompt
  };
}

/**
 * PASS A: Generate Composer Plan (JSON only, no LilyPond)
 */
async function generateComposerPlan(params, progressCallback, costTracking) {
  const { system, user } = buildComposerPlanPrompt(params);

  let parseAttempt = 0;

  while (parseAttempt < MAX_PLAN_PARSE_ATTEMPTS) {
    parseAttempt++;

    progressCallback?.({
      message: `Generating composer plan (attempt ${parseAttempt})...`,
      progress: 5 + (parseAttempt * 5)
    });

    try {
      // Safety guard: check API call limit
      checkAPICallLimit(costTracking);

      // Calculate request size
      const requestSize = system.length + user.length;

      const response = await anthropic.messages.create({
        model: 'claude-sonnet-4-5-20250929',
        max_tokens: 512,
        system: system,
        messages: [{ role: 'user', content: user }]
      });

      let content = response.content[0].text.trim();

      // Track this API call
      trackAPICall(costTracking, 'plan-generate', requestSize, content.length);

      // Strip markdown code blocks if present
      content = content.replace(/^```json?\s*\n?/i, '').replace(/\n?```\s*$/i, '');

      // Parse JSON
      const plan = JSON.parse(content);

      // Validate required fields (new impressionistic brief format)
      const requiredFields = ['tendencies', 'emotion', 'avoid'];
      for (const field of requiredFields) {
        if (!plan[field]) {
          throw new Error(`Missing required field: ${field}`);
        }
      }
      if (!Array.isArray(plan.tendencies) || plan.tendencies.length < 2) {
        throw new Error('tendencies must be an array with at least 2 items');
      }

      console.log('[Composer Plan] ✓ Valid plan generated');
      console.log(JSON.stringify(plan, null, 2));

      return plan;

    } catch (error) {
      console.warn(`[Composer Plan] Parse attempt ${parseAttempt} failed:`, error.message);

      if (parseAttempt >= MAX_PLAN_PARSE_ATTEMPTS) {
        throw new Error(`Failed to generate valid composer plan after ${MAX_PLAN_PARSE_ATTEMPTS} attempts: ${error.message}`);
      }

      // Brief delay before retry
      await new Promise(resolve => setTimeout(resolve, 1000));
    }
  }
}

