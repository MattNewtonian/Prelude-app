/**
 * Safety guard: Check if we've exceeded max API calls
 */
function checkAPICallLimit(costTracking) {
  if (costTracking.totalCalls >= MAX_TOTAL_CLAUDE_CALLS) {
    throw new Error(
      `Safety limit exceeded: job reached ${MAX_TOTAL_CLAUDE_CALLS} API calls. ` +
      `This prevents runaway costs. Adjust MAX_TOTAL_CLAUDE_CALLS if needed.`
    );
  }
}

/**
 * Cost tracking helper
 * Approximate tokens: chars / 4 (rough estimate)
 */
function trackAPICall(costTracking, callType, requestChars, responseChars) {
  const approxInputTokens = Math.ceil(requestChars / 4);
  const approxOutputTokens = Math.ceil(responseChars / 4);

  costTracking.calls.push({
    type: callType,
    requestChars,
    responseChars,
    approxInputTokens,
    approxOutputTokens
  });

  costTracking.totalCalls++;
  costTracking.totalInputTokens += approxInputTokens;
  costTracking.totalOutputTokens += approxOutputTokens;
}

/**
 * Initialize cost tracking object
 */
function createCostTracking() {
  return {
    calls: [],
    totalCalls: 0,
    totalInputTokens: 0,
    totalOutputTokens: 0
  };
}

/**
 * Normalize free text to keep prompts concise and token-efficient.
 */
function compactPromptText(text, maxLength = 240) {
  if (!text || typeof text !== 'string') return '';

  const compact = text.replace(/\s+/g, ' ').trim();
  if (compact.length <= maxLength) return compact;

  return compact.slice(0, maxLength - 3).trimEnd() + '...';
}

/**
 * Build provenance markup block for LilyPond PDF.
 * Appears as a small, muted info block above the score.
 */
function buildProvenanceMarkup(params) {
  const { key, bars, difficulty, style, inspiredBy, prompt } = params;

  const year = new Date().getFullYear();
  const diffLabel = difficulty.charAt(0).toUpperCase() + difficulty.slice(1);

  // Escape for LilyPond string literals
  function escapeLy(str) {
    return str.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  }

  // Truncate prompt if needed
  let shortPrompt = (prompt || '').trim();
  if (shortPrompt.length > 120) {
    shortPrompt = shortPrompt.substring(0, 117).trim() + '...';
  }

  // Get display names for style and composer
  const styleName = style ? (getStylePreset(style)?.name || style) : null;
  const composerName = inspiredBy ? (getComposerInspiration(inspiredBy)?.name || inspiredBy) : null;

  // Build content lines for the markup block
  const lines = [];

  if (shortPrompt) {
    lines.push('"Generated from a natural-language description:"');
    lines.push('\\italic { "' + escapeLy('\u201C' + shortPrompt + '\u201D') + '" }');
    lines.push('\\vspace #0.3');
  }

  lines.push('"Key: ' + escapeLy(key) + ' \u00B7 Bars: ' + bars + ' \u00B7 Difficulty: ' + diffLabel + '"');

  if (styleName) {
    lines.push('"Style: ' + escapeLy(styleName) + '"');
  }
  if (composerName) {
    lines.push('"Inspiration: ' + escapeLy(composerName) + '"');
  }

  lines.push('\\vspace #0.3');
  lines.push('"Generated by Prelude \u00B7 ' + year + '"');

  const indented = lines.map(l => '      ' + l).join('\n');

  return [
    '',
    '\\markup \\fill-line {',
    '  \\center-column {',
    "    \\fontsize #-2 \\with-color #(x11-color 'grey50) \\center-column {",
    indented,
    '    }',
    '    \\vspace #1',
    '  }',
    '}',
    ''
  ].join('\n');
}

/**
 * Inject provenance markup into LilyPond code, before the \\score block.
 */
function injectProvenance(code, provenanceMarkup) {
  const scoreIndex = code.indexOf('\\score');
  if (scoreIndex !== -1) {
    return code.substring(0, scoreIndex) + provenanceMarkup + '\n' + code.substring(scoreIndex);
  }
  // Fallback: prepend after version line
  const versionEnd = code.indexOf('\n');
  if (versionEnd !== -1) {
    return code.substring(0, versionEnd + 1) + provenanceMarkup + '\n' + code.substring(versionEnd + 1);
  }
  return provenanceMarkup + '\n' + code;
}

/**
 * Detect active behavioral mode flags for a given params object.
 * Returns { baroque, jazz, organicTime, antiEtude } booleans.
 * Low threshold — better to over-trigger than under-trigger.
 */
export function getModeFlags(params) {
  const { style, inspiredBy, prompt } = params;

  // Baroque detection
  let baroque = false;
  if (style && ['baroque', 'keyboard', 'partita'].includes(style.toLowerCase())) baroque = true;
  if (inspiredBy && inspiredBy.toLowerCase() === 'bach') baroque = true;
  if (prompt) {
    const lower = prompt.toLowerCase();
    const baroqueKeywords = [
      'bach', 'partita', 'fugue', 'invention', 'baroque', 'contrapuntal',
      'counterpoint', 'prelude and fugue', 'well-tempered', 'toccata',
      'sarabande', 'allemande', 'courante', 'gigue', 'bourrée', 'bourree',
      'gavotte', 'minuet', 'passacaglia', 'chaconne', 'ricercar', 'sinfonia'
    ];
    if (baroqueKeywords.some(k => lower.includes(k))) baroque = true;
  }

  // Jazz detection
  let jazz = false;
  if (style && style.toLowerCase() === 'jazz-tinged') jazz = true;
  if (inspiredBy && inspiredBy.toLowerCase() === 'gershwin') jazz = true;
  if (prompt) {
    const lower = prompt.toLowerCase();
    const jazzKeywords = [
      'jazz', 'swing', 'bebop', 'blues', 'groove', 'groovy', 'funky',
      'syncopat', 'boogie', 'stride', 'ragtime', 'soul', 'bossa', 'latin jazz'
    ];
    if (jazzKeywords.some(k => lower.includes(k))) jazz = true;
  }

  // Impressionist detection
  let impressionist = false;
  if (style && style.toLowerCase() === 'impressionist') impressionist = true;
  if (inspiredBy && ['debussy', 'ravel'].includes(inspiredBy.toLowerCase())) impressionist = true;
  if (prompt) {
    const lower = prompt.toLowerCase();
    const impressionistKeywords = [
      'impressionist', 'debussy', 'ravel', 'clair de lune', 'claire de lune',
      'whole tone', 'impressionism', 'arabesques', 'reverie', 'rêverie', 'nocturne'
    ];
    if (impressionistKeywords.some(k => lower.includes(k))) impressionist = true;
  }

  // Classical detection (Mozart, Haydn)
  let classical = false;
  if (style && style.toLowerCase() === 'classical') classical = true;
  if (inspiredBy && inspiredBy.toLowerCase() === 'mozart') classical = true;
  if (prompt) {
    const lower = prompt.toLowerCase();
    const classicalKeywords = [
      'mozart', 'haydn', 'classical', 'alberti', 'sonata', 'sonatina',
      'minuet and trio', 'rondo', 'periodic', 'galant'
    ];
    if (classicalKeywords.some(k => lower.includes(k))) classical = true;
  }

  // Romantic detection (Chopin, Schubert, Schumann)
  let romantic = false;
  if (style && style.toLowerCase() === 'romantic') romantic = true;
  if (inspiredBy && inspiredBy.toLowerCase() === 'chopin') romantic = true;
  if (prompt) {
    const lower = prompt.toLowerCase();
    const romanticKeywords = [
      'chopin', 'romantic', 'cantabile', 'lyrical', 'nocturne style',
      'schubert', 'schumann', 'liszt', 'singing melody', 'expressive rubato'
    ];
    if (romanticKeywords.some(k => lower.includes(k))) romantic = true;
  }

  // Minimal detection (Glass, ambient, minimalist)
  let minimal = false;
  if (style && style.toLowerCase() === 'minimal') minimal = true;
  if (inspiredBy && inspiredBy.toLowerCase() === 'glass') minimal = true;
  if (prompt) {
    const lower = prompt.toLowerCase();
    const minimalKeywords = [
      'glass', 'minimal', 'minimalist', 'ambient', 'ostinato', 'repetit',
      'hypnotic', 'drone', 'meditative', 'arvo pärt', 'part', 'satie'
    ];
    if (minimalKeywords.some(k => lower.includes(k))) minimal = true;
  }

  // Cinematic detection (Zimmer, film score)
  let cinematic = false;
  if (style && style.toLowerCase() === 'cinematic') cinematic = true;
  if (inspiredBy && inspiredBy.toLowerCase() === 'zimmer') cinematic = true;
  if (prompt) {
    const lower = prompt.toLowerCase();
    const cinematicKeywords = [
      'zimmer', 'cinematic', 'film score', 'soundtrack', 'epic', 'cinematic build',
      'nils frahm', 'ludovico', 'yann tiersen', 'movie music', 'trailer'
    ];
    if (cinematicKeywords.some(k => lower.includes(k))) cinematic = true;
  }

  // Baroque takes priority over everything
  if (baroque) { jazz = false; impressionist = false; classical = false; romantic = false; minimal = false; cinematic = false; }
  // Prevent style conflicts (first detected wins after baroque)
  if (jazz) { impressionist = false; classical = false; romantic = false; minimal = false; cinematic = false; }
  if (impressionist) { classical = false; romantic = false; minimal = false; cinematic = false; }
  if (classical) { romantic = false; minimal = false; cinematic = false; }
  if (romantic) { minimal = false; cinematic = false; }
  if (minimal) { cinematic = false; }

  return {
    baroque,
    jazz,
    impressionist,
    classical,
    romantic,
    minimal,
    cinematic,
    organicTime: !baroque && !jazz && !impressionist && !classical && !romantic && !minimal && !cinematic,
    antiEtude: !baroque && !jazz && !impressionist && !classical && !romantic && !minimal && !cinematic
  };
}

